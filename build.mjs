/**
 * Bundles `src/*.mjs` into the single `client.js` the shell loads.
 *
 * The client bundle format is a `window.__ModuleLoader__.load({ id, factory })`
 * wrapper whose factory is one closure: several source modules, no import
 * statements. Each source file below is a fragment written in that style — no
 * `import`, everything shared through the closure scope — and this script joins
 * them, strips the leading `export ` keyword the fragments declare for Node tests,
 * and injects the dictionaries from `locale/*.json` so the shipped bundle and the
 * test harness read the same strings.
 *
 * Run: node build.mjs   (writes client.js next to this file)
 */
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import vm from 'node:vm'

const here = path.dirname(fileURLToPath(import.meta.url))
const PARTS = ['engine.mjs', 'zip.mjs', 'ui.mjs', 'panels.mjs']
const ENTRY = 'entry.mjs'
const PACKAGE_NAME = '@local/design-studio'
const LOCALES = ['en', 'zh']

function stripExports(source) {
  return source.replace(/^export /gm, '')
}

async function readPart(name) {
  const file = path.join(here, 'src', name)
  const raw = await readFile(file, 'utf8')
  return stripExports(raw).trimEnd()
}

const dictionaries = {}
for (const locale of LOCALES) {
  const file = path.join(here, 'locale', `${locale}.json`)
  dictionaries[locale] = JSON.parse(await readFile(file, 'utf8'))
}

const parts = []
for (const name of PARTS) {
  parts.push(`    /* ------------------------------------------------- ${name} */\n`)
  parts.push(await readPart(name))
  parts.push('\n\n')
}
parts.push('    /* ------------------------------------------------- dictionaries */\n')
parts.push(`    const DS_DICT = ${JSON.stringify(dictionaries, null, 2)}\n\n`)
parts.push(await readPart(ENTRY))
parts.push('\n')

const body = parts.join('')

const bundle = `/* Design Studio — generated by build.mjs from src/*.mjs; do not edit by hand. */
window.__ModuleLoader__.load({
  id: '${PACKAGE_NAME}',
  factory(require) {
    const React = require('react')
    const h = React.createElement

${body}  },
})
`

const target = path.join(here, 'client.js')
await writeFile(target, bundle, 'utf8')

// Fail the build on a syntactically invalid bundle instead of discovering it in the shell.
let loaded = null
const sandbox = {
  window: {
    __ModuleLoader__: {
      load: (entry) => {
        loaded = entry
      },
    },
  },
}
try {
  new vm.Script(bundle, { filename: 'client.js' })
  vm.runInNewContext(bundle, sandbox, { filename: 'client.js' })
} catch (error) {
  console.error('[build] client.js failed to load:\n' + (error && error.stack ? error.stack : error))
  process.exitCode = 1
  throw error
}
if (!loaded || loaded.id !== PACKAGE_NAME) throw new Error('[build] bundle did not register ' + PACKAGE_NAME)
if (typeof loaded.factory !== 'function' || loaded.factory.length !== 1) {
  throw new Error('[build] factory(require) is not a one-argument function')
}

const size = Buffer.byteLength(bundle, 'utf8')
console.log(
  '[build] client.js ' + (size / 1024).toFixed(1) + ' KB · ' + PARTS.length + ' parts + entry · locales ' + LOCALES.join(', '),
)
